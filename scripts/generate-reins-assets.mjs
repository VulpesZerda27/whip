/* eslint-env node, es2022 */
import { copyFile, mkdir, readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { encode, toSvg } from '@verevoir/qr';
import sharp from 'sharp';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const brand = resolve(root, 'assets/reins');
const resources = resolve(root, 'android/app/src/main/res');
const installUrl =
  'https://github.com/VulpesZerda27/whip/blob/feat/mobile-chat-mode/docs/chat-mode.md';
const transparent = { r: 0, g: 0, b: 0, alpha: 0 };
const normal = await readFile(resolve(brand, 'reins-icon.png'));
const dark = await readFile(resolve(brand, 'reins-icon-dark.png'));

async function save(relativePath, contents) {
  const destination = resolve(root, relativePath);
  await mkdir(dirname(destination), { recursive: true });
  await writeFile(destination, contents);
}

// Android adaptive layers are 108dp with a 72dp visible viewport. Padding the
// supplied square keeps its composition and ring intact inside launcher masks.
async function adaptiveLayer(input) {
  return sharp(input)
    .resize(1024, 1024)
    .extend({
      top: 256,
      bottom: 256,
      left: 256,
      right: 256,
      background: transparent,
    })
    .png()
    .toBuffer();
}

for (const [input, qualifier] of [
  [normal, ''],
  [dark, '-night'],
]) {
  const layer = await adaptiveLayer(input);
  await save(
    `android/app/src/main/res/drawable${qualifier}-nodpi/reins_foreground.png`,
    layer,
  );
  if (!qualifier) await save('assets/reins/android-foreground.png', layer);
  const corner = await sharp(input)
    .extract({ left: 0, top: 0, width: 1, height: 1 })
    .removeAlpha()
    .raw()
    .toBuffer();
  const color = `#${corner.subarray(0, 3).toString('hex')}`;
  await save(
    `android/app/src/main/res/values${qualifier}/colors.xml`,
    `<?xml version="1.0" encoding="utf-8"?>\n<resources>\n    <color name="ic_launcher_whip_background">${color}</color>\n</resources>\n`,
  );
}

// The supplied tinted artwork uses luminance for its mask. Android themed and
// notification icons require the same information in the alpha channel.
const { data, info } = await sharp(resolve(brand, 'reins-icon-tinted.png'))
  .removeAlpha()
  .greyscale()
  .raw()
  .toBuffer({ resolveWithObject: true });
const rgba = Buffer.alloc(info.width * info.height * 4, 255);
for (let i = 0; i < info.width * info.height; i++)
  rgba[i * 4 + 3] = data[i * info.channels];
const mask = await sharp(rgba, {
  raw: { width: info.width, height: info.height, channels: 4 },
})
  .png()
  .toBuffer();
const adaptiveMask = await adaptiveLayer(mask);
await save('assets/reins/android-monochrome.png', adaptiveMask);
await save(
  'android/app/src/main/res/drawable-nodpi/reins_monochrome.png',
  adaptiveMask,
);
await save(
  'android/app/src/main/res/drawable-nodpi/reins_notification.png',
  await sharp(mask).resize(96, 96).png().toBuffer(),
);

const bitmap = name => `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-reins-assets.mjs. -->
<bitmap xmlns:android="http://schemas.android.com/apk/res/android"
    android:src="@drawable/${name}" android:gravity="fill" />
`;
await save(
  'android/app/src/main/res/drawable/ic_launcher_whip_foreground.xml',
  bitmap('reins_foreground'),
);
await save(
  'android/app/src/main/res/drawable/ic_notification_whip.xml',
  bitmap('reins_notification'),
);

for (const [version, themed] of [
  [26, false],
  [33, true],
]) {
  const xml = `<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by scripts/generate-reins-assets.mjs. -->
<adaptive-icon xmlns:android="http://schemas.android.com/apk/res/android">
    <background android:drawable="@color/ic_launcher_whip_background" />
    <foreground android:drawable="@drawable/ic_launcher_whip_foreground" />
${themed ? '    <monochrome android:drawable="@drawable/reins_monochrome" />\n' : ''}</adaptive-icon>
`;
  for (const name of [
    'ic_launcher_whip_adaptive',
    'ic_launcher_whip_adaptive_round',
  ])
    await save(
      `android/app/src/main/res/mipmap-anydpi-v${version}/${name}.xml`,
      xml,
    );
}

for (const [density, size] of [
  ['mdpi', 48],
  ['hdpi', 72],
  ['xhdpi', 96],
  ['xxhdpi', 144],
  ['xxxhdpi', 192],
]) {
  const square = await sharp(normal).resize(size, size).png().toBuffer();
  const circle = Buffer.from(
    `<svg width="${size}" height="${size}"><circle cx="${size / 2}" cy="${size / 2}" r="${size / 2}" fill="white"/></svg>`,
  );
  const round = await sharp(square)
    .composite([{ input: circle, blend: 'dest-in' }])
    .png()
    .toBuffer();
  for (const name of ['ic_launcher', 'ic_launcher_whip_adaptive']) {
    await writeFile(
      resolve(resources, `mipmap-${density}/${name}.png`),
      square,
    );
    await writeFile(
      resolve(resources, `mipmap-${density}/${name}_round.png`),
      round,
    );
  }
}

await copyFile(
  resolve(brand, 'reins-icon.png'),
  resolve(root, 'assets/icon.png'),
);
for (const folder of ['assets/AppIcon.icon', 'ios/HerdR/AppIcon.icon'])
  await copyFile(
    resolve(brand, 'reins-icon.png'),
    resolve(root, folder, 'Assets/reins-icon.png'),
  );
const [qr] = encode(installUrl);
await save(
  'assets/reins/install-qr.png',
  await sharp(Buffer.from(toSvg(qr)))
    .resize(720, 720)
    .png()
    .toBuffer(),
);
console.log(
  'Generated Reins launcher, themed, notification, iOS and install QR assets.',
);
